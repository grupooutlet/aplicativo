const assert=require('node:assert/strict');
const {prepare,canonical,plainText}=require('../scripts/prepare-forte-import.cjs');
const {flight}=require('../scripts/import-forte-catalog.cjs');
const original={sourceId:1,url:'https://www.forteoutlet.com.br/produto/1',title:'Sofá Lima 2.00m Linho Cinza',price:997,category:'Sofás',images:['source1'],descriptionHtml:'<p>Descrição &amp; medidas</p><ul><li>Confortável</li></ul>',variants:[{id:10,nome:'Cinza',preco:997,controlar_estoque:true,stock_info:{quantidade_atual:3},produto_variacao_valor:[{atributo_valor:{atributos:{nome:'Cor'},valor:'Cinza'}},{atributo_valor:{atributos:{nome:'Medida'},valor:'2,00'}}]}]};
const existing={products:[{id:4,name:'Sofá Lima 2,00m Linho Cinza',cost:900,stock:7}]};
const before=JSON.stringify(existing);
const manifest={source1:{verified:true,url:'https://own.example/photo.jpg'}};
const items=prepare([original,{...original,sourceId:2,title:'Sofá Lima 2.00m Linho Bege',images:[]},{...original,sourceId:3,title:'Roupeiro Zeus',category:null}],existing,manifest);
assert.equal(items[0].product.active,false);
assert.deepEqual(items[0].product.importInfo.duplicateOf,[4]);
assert.equal(items[1].product.importInfo.reasons.includes('duplicate'),false,'different colors must not be merged');
assert.deepEqual(items[1].product.importInfo.reasons,['missing_photos']);
assert.equal(items[2].product.category,'Guarda-roupas');
assert.equal(items[2].product.active,true);
assert.equal(items[2].product.stock,3);
assert.equal(items[2].product.price,997);
assert.deepEqual(items[2].product.variations,[{name:'Cor',values:['Cinza']},{name:'Tamanho',values:['2,00m']}]);
assert.equal(items[2].product.sourceVariants[0].sourceId,10);
assert.equal(JSON.stringify(existing),before,'existing products, costs and stock are never mutated');
assert.throws(()=>prepare([original],existing,{}),/Missing verified copy/);
const eleven=Array.from({length:11},(_,i)=>'image'+i);
assert.equal(prepare([{...original,images:eleven}],{products:[]},Object.fromEntries(eleven.map(x=>[x,{verified:true,url:x}])))[0].product.images.length,11);
assert.notEqual(canonical('Sofá Lima 2.00m Cinza'),canonical('Sofá Lima 2.10m Cinza'));
assert.equal(plainText('<script>bad()</script><p>Bem &amp; bom</p><p>2&nbsp;m</p>'),'Bem & bom\n2 m');
const title='Título com ç e descrição grande';
const records=`a:T${Buffer.byteLength(title).toString(16)},${title}b:${JSON.stringify(['$','div',null,{title:'$a'}])}\n`;
const html='<script>self.__next_f.push('+JSON.stringify([1,records])+')</script>';
assert.equal(flight(html).resolve('$b:props:title'),title,'Flight text lengths use UTF-8 bytes, references resolve without executing source JavaScript');
console.log('Catalog import: duplicate protection, photo coverage, stock, variations and safe source parsing verified.');
